##########################################################################
# This script does the following:
# 1. Loads dataset_baseline_meds_analysed.arrow
# 2. Loads analysis/config/medication_of_interest.csv names + filepaths
# 3. Loops through each medication of interest and builds matching
#    bnf_substance_codes from the bnf_code column
# 4. Writes one one-row-per-patient dataset per medication of interest,
#    that has two columns:
#     - patient_id of person prescribed the medication at baseline
#     - days_before_index_most_recent_prescription (the most-recent
#    value across matched substances, for a medication of interest that
#    maps to more than one bnf_substance_code)
# 5. Outputs a diagnostic for each medication that reports the difference
#    in number of chronic baseline users per medicine between the main
#    analytical dataset (that maps dmd-BNF using NHSBSA file at docs/)
#    and if just using dmd-codes generated by OpenCodelists
##########################################################################

# Import libraries and functions ----------------------------------------------
message("Import libraries")
library(here)
library(arrow)
library(tidyverse)
library(fs)
source(here::here("analysis", "config", "config.r"))
source(here::here(
  "analysis",
  "r_functions",
  "medications",
  "fn_summarise_chronic_meds.r"
))
source(here::here(
  "analysis",
  "r_functions",
  "utilities",
  "fn_disclosure_control.r"
))

# Create output folders -------------------------------------------------------
message("Create output folders")
dir_create(here::here("output", "data"))
dir_create(here::here(
  "output",
  "data_descriptions",
  "build_moi_datasets_at_baseline"
))

# Import dates -----------------------------------------------------------
study_dates <- lapply(study_dates, function(x) as.Date(x))

# Load datasets ----------------------------------------------------------------
message("Load dataset_baseline_meds_analysed.arrow")
dataset_baseline_meds_analysed <- read_feather(here::here(
  "output",
  "data",
  "dataset_baseline_meds_analysed.arrow"
))

message("Load dataset_baseline_meds_processed.arrow")
dataset_baseline_meds_processed <- read_feather(here::here(
  "output",
  "data",
  "dataset_baseline_meds_processed.arrow"
))

# Load medication-of-interest reference csv ------------------------------------
medications_of_interest <- read_csv(
  here::here("analysis", "config", "medication_of_interest.csv"),
  show_col_types = FALSE
)

# Build and save one dataset per medication of interest -----------------------
message("Build medication-of-interest at baseline datasets")

codelist_coverage_summary <- list()

# Loop over each row of the medications_of_interest.csv file
for (i in seq_len(nrow(medications_of_interest))) {
  name <- medications_of_interest$name[i]
  codelist <- read_csv(
    medications_of_interest$codelist_path[i],
    col_types = cols(.default = "c") # force all codes to strings
  )

  # list of unique BNF substance codes per codelist
  substance_codes <- codelist |>
    mutate(bnf_substance_code = substr(bnf_code, 1, 9)) |>
    distinct(bnf_substance_code) |>
    pull(bnf_substance_code)

  # pull the patient_ids and days_before_index of most recent prescription
  patients_on_medication_of_interest <- dataset_baseline_meds_analysed |>
    filter(bnf_substance_code %in% substance_codes) |>
    group_by(patient_id) |>
    summarise(
      # in the case of multiple hits take most recent one
      days_before_index_most_recent_prescription = min(
        days_before_index_most_recent_prescription
      ),
      .groups = "drop"
    )

  message(sprintf(
    "--- %s: %d patients",
    name,
    nrow(patients_on_medication_of_interest)
  ))

  write_feather(
    patients_on_medication_of_interest,
    here::here("output", "data", paste0("dataset_", name, "_at_baseline.arrow"))
  )

  # DIAGNOSTIC ##################################################################
  # Importantly dataset_baseline_meds_analysed$bnf_substance_code was created
  # by mapping patient's dmd codes to BNF using the NHS BSA BNF-dmd mapping.
  # The code below computes what the number of patients taken forward would be
  # if OpenCodelist-derived dmd codes were used instead.
  #
  # The NHS BSA dmd-BNF mapping is newer so picks up new codes. It also imputed
  # missing BNF-dmd mappings in situations where BNF codes were missing.
  #
  # Therefore the OpenCodelist dmd-codelist contains fewer codes. It is however
  # likely to cover THE VAST majority of the dmd_codes actually used in real life.
  # This diagnostic will check this.
  ################################################################################
  opencodelist_dmd_codes <- unique(codelist$code)

  # this step goes back to the just processed data (before dmd_codes were collapsed)
  chronic_flags_opencodelist <- fn_flag_chronic_meds(
    data = dataset_baseline_meds_processed |>
      filter(
        bnf_substance_code %in% substance_codes,
        route_cat == "oral",
        dmd_code %in% opencodelist_dmd_codes
      ),
    config = chronic_med_definitions$base,
    index_date = study_dates$index_date,
    config_name = "base"
  )

  patients_covered_by_opencodelist <- chronic_flags_opencodelist |>
    filter(is_chronic_base) |>
    pull(patient_id)

  n_total <- nrow(patients_on_medication_of_interest)
  n_not_covered <- patients_on_medication_of_interest |>
    filter(!patient_id %in% patients_covered_by_opencodelist) |>
    nrow()

  # apply SDC suppression to counts first, then derive the rate from the
  # already-suppressed counts, so a rate is never calculated from an
  # unsuppressed small count (docs.opensafely.org/outputs/sdc/)
  n_total_sdc <- fn_apply_sdc(n_total)
  n_not_covered_sdc <- fn_apply_sdc(n_not_covered)

  codelist_coverage_summary[[name]] <- tibble(
    medication_name = name,
    n_chronic_baseline = n_total_sdc,
    n_not_covered_by_opencodelist = n_not_covered_sdc,
    pct_not_covered_by_opencodelist = round(
      100 * n_not_covered_sdc / n_total_sdc,
      2
    )
  )
}

message("--- Write codelist coverage diagnostic")
bind_rows(codelist_coverage_summary) |>
  write_csv(here::here(
    "output",
    "data_descriptions",
    "build_moi_datasets_at_baseline",
    "moi_pt_coverage_NHSBSA_vs_OpenCodelists.csv"
  ))
